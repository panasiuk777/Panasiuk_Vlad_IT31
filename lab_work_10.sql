-- =========================================================
-- Практична робота №10
-- Тема: Відбір груп за допомогою HAVING
-- База даних: cinema
-- =========================================================


-- =========================================================
-- Завдання 1
-- HAVING + COUNT
-- Групуємо сеанси за залами та залишаємо зали,
-- у яких більше 1 сеансу.
-- =========================================================

SELECT hall_id,
       COUNT(*) AS screenings_count
FROM screenings
GROUP BY hall_id
HAVING COUNT(*) > 1;

-- Результат:
-- hall_id | screenings_count
-- 1       | 2


-- =========================================================
-- Завдання 2
-- HAVING + AVG
-- Знаходимо середню ціну квитка для кожного залу
-- та залишаємо групи із середньою ціною понад 150.
-- =========================================================

SELECT hall_id,
       AVG(ticket_price) AS average_price
FROM screenings
GROUP BY hall_id
HAVING AVG(ticket_price) > 150;

-- Результат:
-- hall_id | average_price
-- 2       | 180.0


-- =========================================================
-- Завдання 3
-- WHERE + GROUP BY + HAVING
-- WHERE фільтрує окремі записи,
-- HAVING фільтрує вже сформовані групи.
-- =========================================================

SELECT hall_id,
       AVG(ticket_price) AS average_price
FROM screenings
WHERE ticket_price >= 100
GROUP BY hall_id
HAVING AVG(ticket_price) > 120;

-- Результат:
-- hall_id | average_price
-- 1       | 135.0
-- 2       | 180.0


-- =========================================================
-- Завдання 4
-- НАВМИСНА ПОМИЛКА
-- Агрегатну функцію COUNT() не можна використовувати
-- у WHERE.
-- =========================================================

SELECT hall_id,
       COUNT(*) AS screenings_count
FROM screenings
WHERE COUNT(*) > 1
GROUP BY hall_id;

-- Точний текст помилки SQLite:
-- misuse of aggregate: COUNT()

-- Причина:
-- WHERE виконується до GROUP BY та агрегації,
-- тому COUNT(*) ще не існує на момент виконання WHERE.
-- Для фільтрації груп потрібно використовувати HAVING.


-- =========================================================
-- Завдання 5
-- LEFT JOIN + GROUP BY + HAVING
-- Знаходимо зали, у яких менше 2 сеансів,
-- включаючи зали, де немає жодного сеансу.
-- =========================================================

SELECT halls.id,
       halls.name,
       COUNT(screenings.id) AS screenings_count
FROM halls
LEFT JOIN screenings
       ON screenings.hall_id = halls.id
GROUP BY halls.id
HAVING COUNT(screenings.id) < 2;

-- Результат:
-- id | name     | screenings_count
-- 2  | Зал 2    | 1
-- 3  | VIP зал  | 0


