-- Практика 9. Формування запитів з групуванням даних
-- Фактова таблиця: screenings


-- ============================================================
-- Завдання 1. GROUP BY по одній колонці
-- ============================================================

SELECT movie_id, COUNT(*) AS screenings_count
FROM screenings
GROUP BY movie_id;

-- Результат:
-- 1 | 1
-- 2 | 1
-- 3 | 1


-- ============================================================
-- Завдання 2. JOIN + GROUP BY
-- ============================================================

SELECT movies_old.title, COUNT(screenings.id) AS screenings_count
FROM movies_old
LEFT JOIN screenings ON screenings.movie_id = movies_old.id
GROUP BY movies_old.id;

-- Результат:
-- Інтерстеллар   | 1
-- Початок        | 1
-- Король Лев     | 1
-- Тестовий фільм | 0


-- ============================================================
-- Завдання 3. Кілька агрегатних функцій
-- ============================================================

SELECT movie_id,
       COUNT(*) AS screenings_count,
       AVG(ticket_price) AS average_ticket_price
FROM screenings
GROUP BY movie_id;

-- Результат:
-- 1 | 1 | 150.0
-- 2 | 1 | 180.0
-- 3 | 1 | 120.0


-- ============================================================
-- Завдання 4. GROUP BY за двома колонками
-- ============================================================

SELECT hall_id, screening_date, COUNT(*) AS screenings_count
FROM screenings
GROUP BY hall_id, screening_date;

-- Результат:
-- 1 | 2026-10-01 | 1
-- 1 | 2026-10-02 | 1
-- 2 | 2026-10-01 | 1


-- Отримано 3 рядки.
-- Унікальних hall_id: 2.
-- Унікальних screening_date: 2.
-- Можливих комбінацій: 2 * 2 = 4.
-- Фактично є 3 комбінації.


-- ============================================================
-- Завдання 5. Пастка "колонка поза GROUP BY"
-- ============================================================

SELECT hall_id, screening_date, COUNT(*) AS screenings_count
FROM screenings
GROUP BY hall_id;

-- Результат першого запуску:
-- 1 | 2026-10-01 | 2
-- 2 | 2026-10-01 | 1

-- Результат другого запуску:
-- 1 | 2026-10-01 | 2
-- 2 | 2026-10-01 | 1

-- Результати двох запусків однакові.
-- Але screening_date не входить у GROUP BY.
-- Для hall_id = 1 є дві різні дати:
-- 2026-10-01 та 2026-10-02.
-- SQLite дозволяє такий запит і повертає значення
-- з одного з рядків групи, але гарантії щодо вибору
-- конкретного значення немає.
-- PostgreSQL такий запит відхилить з помилкою.
